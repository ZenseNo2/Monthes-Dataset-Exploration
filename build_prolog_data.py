"""
build_prolog_data.py
====================
Converts the cleaned dataset into Prolog FACTS  ->  traceability_data.pl

    python build_prolog_data.py

Run it again whenever you edit anything in ./dataset.
The RULES live in traceability_fol.pl (hand written, that is the file to study).
"""

import re
import sys
from pathlib import Path

from traceability_dataset import DEFAULT_DIR, data_quality_report, load_dataset

OUT = Path(__file__).resolve().parent / "traceability_data.pl"


def q(text: str) -> str:
    """Prolog quoted atom: 'text' (escape backslash and single quote)."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def atom(text: str) -> str:
    """Unquoted atom if it is a plain lower-case word, otherwise quoted."""
    return text if re.fullmatch(r"[a-z][a-z0-9_]*", text) else q(text)


def render(ds) -> str:
    L = []
    L.append("% AUTO-GENERATED by build_prolog_data.py  -  do not edit by hand.")
    L.append("% Every line below is one FACT taken from the markdown dataset.\n")

    L.append("% requirement(Id, Text).")
    L += [f"requirement({atom(r)}, {q(t)})." for r, t in ds.requirements.items()]

    L.append("\n% design_class(Id).            every design element used anywhere")
    L += [f"design_class({atom(d)})." for d in ds.designs]
    L.append("\n% declared_design(Id).         listed in design_classes.md")
    L += [f"declared_design({atom(d)})." for d in ds.designs if d in ds.declared_designs]
    L.append("\n% stereotype(Id, Kind).        from the C_/M_/V_ prefix")
    L += [f"stereotype({atom(d)}, {k})." for d, k in ds.designs.items()]

    L.append("\n% code_file(Path).             every file used anywhere")
    L += [f"code_file({q(c)})." for c in ds.codes]
    L.append("\n% declared_code(Path).         listed in source_codes.md")
    L += [f"declared_code({q(c)})." for c in ds.codes if c in ds.declared_codes]

    L.append("\n% req_design(Req, Design).     rows of req-to-design.md marked 1")
    L += [f"req_design({atom(r)}, {atom(d)})." for r, d in ds.req_design]
    L.append("\n% design_code(Design, File).   rows of design-to-code.md marked 1")
    L += [f"design_code({atom(d)}, {q(c)})." for d, c in ds.design_code]
    L.append("\n% req_code(Req, File).         rows of req-to-code.md marked 1 (recorded ground truth)")
    L += [f"req_code({atom(r)}, {q(c)})." for r, c in ds.req_code]
    return "\n".join(L) + "\n"


def main():
    data_dir = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DIR
    ds = load_dataset(data_dir)
    OUT.write_text(render(ds), encoding="utf-8")

    print(f"Wrote {OUT.name}\n")
    print("Automatic cleaning applied:")
    for m in ds.cleaning_log:
        print("  -", m)
    print("\nData-quality warnings (kept in the data, but you should know about them):")
    for m in data_quality_report(ds):
        print("  -", m)
    print("\nCounts:")
    print(f"  requirements      : {len(ds.requirements)}")
    print(f"  design elements   : {len(ds.designs)} ({len(ds.declared_designs)} declared)")
    print(f"  code files        : {len(ds.codes)} ({len(ds.declared_codes)} declared)")
    print(f"  req_design facts  : {len(ds.req_design)}")
    print(f"  design_code facts : {len(ds.design_code)}")
    print(f"  req_code facts    : {len(ds.req_code)}")


if __name__ == "__main__":
    main()
